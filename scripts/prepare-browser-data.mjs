import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {parseArgs} from 'node:util';
import {browserPayloads,writeBrowserPayloads,writeBrowserRegistry,cleanBrowserPayloads,readHousingPayload,attachHousingRows} from '../server/browser-export.mjs';
import {housingBindingsMap} from '../src/housing-wire.mjs';
import {createHash} from 'node:crypto';
import {buildSearchIndex} from '../src/search-index.mjs';
import {validateIdentityMap,validateIdentitySearch} from '../src/apartment-identity.mjs';
import {readApartmentInformationFile} from '../server/apartment-information-files.mjs';
import {mapTilePayloads} from '../server/map-tiles.mjs';
import {atomicWrite,checkedBytes} from '../server/storage.mjs';
import {secretValues,paths} from '../server/storage.mjs';
const root=fileURLToPath(new URL('../',import.meta.url)),{values}=parseArgs({options:{'public-root':{type:'string'}}});
const publicRoot=path.resolve(values['public-root']||path.join(root,'public')),folder=path.join(publicRoot,'data'),target=path.join(publicRoot,'query-data');
const manifest=JSON.parse(fs.readFileSync(path.join(folder,'manifest.json'))),secrets=secretValues(paths.env);
const groups=new Map(Object.entries(manifest.districts).map(([code,item])=>[code,JSON.parse(fs.readFileSync(path.join(folder,item.file)))]));
const housing=readHousingPayload(folder,manifest,secrets),bindings=housing?housingBindingsMap(housing):null;
const queryGroups=bindings?new Map([...groups].map(([code,rows])=>[code,attachHousingRows(rows,bindings)])):groups;
const {payloads,districts}=browserPayloads(queryGroups,secrets,{housing:manifest.housing});
const mapFolder=path.join(publicRoot,'apartment-map'),mapManifest=JSON.parse(fs.readFileSync(path.join(mapFolder,'manifest.json')));
const masters=JSON.parse(fs.readFileSync(path.join(mapFolder,mapManifest.apartments.file)));
const identity=readApartmentInformationFile(publicRoot,manifest,{required:mapManifest.version===2});
if(manifest.apartment_information&&mapManifest.apartment_information_generation!==identity.generation)throw Error('지도와 공통 아파트 정보 생성 버전이 다릅니다. 자료를 다시 내보내세요.');
if(mapManifest.version===2)validateIdentityMap(masters,identity);
const searchMasters=identity?identity.apartments:masters;
const catalogs=new Map(Object.entries(districts).map(([code,meta])=>[code,JSON.parse(payloads.get(meta.file)).catalog]));
const searchItems=buildSearchIndex(catalogs,manifest.regions,searchMasters);
if(identity)validateIdentitySearch(searchItems,identity);
const searchBytes=checkedBytes(JSON.stringify(searchItems),secrets),searchHash=createHash('sha256').update(searchBytes).digest('hex');
const search={file:'search-'+searchHash.slice(0,12)+'.json',sha256:searchHash,bytes:searchBytes.length,sources:Object.fromEntries(Object.entries(manifest.districts).map(([code,d])=>[code,d.sha256])),...(housing?{housing_sha256:manifest.housing.sha256}:{}),...(identity?.generation?{apartment_information_generation:identity.generation}:{})};
payloads.set(search.file,searchBytes);
writeBrowserPayloads(target,payloads);
const tilesFolder=path.join(publicRoot,'map-data'),geometry=JSON.parse(fs.readFileSync(path.join(mapFolder,mapManifest.boundaries.file)));
const tileData=mapTilePayloads(geometry,mapManifest.boundaries.sha256,value=>checkedBytes(JSON.stringify(value),secrets));
if(identity?.generation){tileData.manifest.apartment_information_generation=identity.generation;tileData.payloads.set('manifest.json',checkedBytes(JSON.stringify(tileData.manifest),secrets));}
fs.mkdirSync(tilesFolder,{recursive:true});
for(const [file,bytes] of tileData.payloads)atomicWrite(path.join(tilesFolder,file),bytes);
for(const file of fs.readdirSync(tilesFolder))if(/^tile-\d+_\d+-[a-f0-9]{12}\.json$/.test(file)&&!tileData.payloads.has(file))fs.unlinkSync(path.join(tilesFolder,file));
console.log('통합 검색 '+JSON.parse(searchBytes).length+'개 · 지도 경계 조각 '+tileData.manifest.tiles.length+'개 준비 완료');
if(identity?.generation)for(const district of Object.values(districts))district.apartment_information_generation=identity.generation;
writeBrowserRegistry(target,manifest,districts,secrets,{search,...(identity?.generation?{apartment_information_generation:identity.generation}:{})});
cleanBrowserPayloads(target,payloads);
console.log(`검색 목록 ${Object.keys(districts).length}개 및 월별 조회 파일 ${payloads.size-Object.keys(districts).length}개 준비 완료`);
